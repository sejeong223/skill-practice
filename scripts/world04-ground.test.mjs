import assert from 'node:assert/strict';
import test from 'node:test';
import { requireTS, world04Harness } from './world04-test-fixtures.mjs';
const { getWorld04Layout } = requireTS('../src/game/data/world04Scrapyard.ts');
const { createGroundState, advanceGroundState } = requireTS('../src/game/systems/world04GroundState.ts');
const { World04GroundSystem } = requireTS('../src/game/systems/World04GroundSystem.ts');
const layout = getWorld04Layout('world-04-stage-4');
const def = kind => layout.objects.find(o => o.kind === kind);
const sample = (center = 0, bottom = 504) => ({ before: { x: center - 40, y: bottom - 40, width: 72, height: 40 }, after: { x: center - 36, y: bottom - 40, width: 72, height: 40 }, grounded: true, velocityY: 0, canLaunch: true });
const atTime = (d, ms) => advanceGroundState(d, { ...createGroundState(d), started: true, elapsedMs: ms }, sample(), 0);
test('cable, belt and press exact period boundaries and no pre-trigger ticking', () => {
  const c = def('cable'); assert.equal(atTime(c, 209).risk, 'none'); assert.equal(atTime(c, 210).risk, 'attack');
  assert.equal(atTime(c, 1950).frame, 1); assert.equal(atTime(c, 2200).risk, 'none');
  const b = def('belt'); assert.equal(atTime(b, 2399).conveyorVelocityX, -90); assert.equal(atTime(b, 2399).warning, true); assert.equal(atTime(b, 2400).conveyorVelocityX, 90);
  const p = def('press'); assert.equal(atTime(p, 700).warning, true); assert.equal(atTime(p, 940).dangerRects.length, 0);
  assert.equal(atTime(p, 1070).dangerRects[0].width, 32); assert.equal(atTime(p, 1200).dangerRects[0].width, 64);
  assert.equal(atTime(p, 1830).dangerRects[0].width, 32); assert.equal(atTime(p, 1960).dangerRects.length, 0);
  let s = createGroundState(c); for (let i = 0; i < 50; i++) s = advanceGroundState(c, s, sample(), 50).state;
  assert.equal(s.elapsedMs, 0); assert.equal(s.started, false);
});
test('tire launches once, requires leaving and landing; gate retries only after release', () => {
  const d = def('tire'), on = sample(d.rect.x + 36), off = sample(d.rect.x - 20);
  let step = advanceGroundState(d, createGroundState(d), on, 16); assert.equal(step.launchVelocityY, -620);
  step = advanceGroundState(d, step.state, on, 16); assert.equal(step.launchVelocityY, null);
  step = advanceGroundState(d, step.state, off, 16); assert.equal(step.state.armed, true);
  assert.equal(advanceGroundState(d, step.state, on, 16).launchVelocityY, -620);
  const g = def('plate-gate'), down = sample(g.plate.x + 20);
  step = advanceGroundState(g, createGroundState(g), down, 16); assert.equal(step.blockingRect, null);
  for (let i = 0; i < 16; i++) step = advanceGroundState(g, step.state, down, 50);
  assert.equal(step.blockingRect, null); step = advanceGroundState(g, step.state, down, 50); assert.equal(step.risk, 'physical');
  for (let i = 0; i < 20; i++) step = advanceGroundState(g, step.state, down, 50);
  assert.equal(step.state.phase, 'rearming'); assert.equal(step.risk, 'none');
  step = advanceGroundState(g, step.state, sample(0), 16); assert.equal(step.state.phase, 'closed');
  step = advanceGroundState(g, step.state, down, 16); assert.equal(step.state.phase, 'open');
});
test('runtime damage classification, pause, synchronous reset, surface sampling and teardown', () => {
  const cable = def('cable'), scrap = def('scrap');
  const h = world04Harness(cable.triggerX - 40); let cleared = 0;
  const controller = { clearSurfaceModifier() { cleared++; }, launchFromSurface() { return true; } };
  const system = new World04GroundSystem(h.scene, h.player, controller, { ...layout, objects: [cable, scrap, ...layout.objects.filter(o => o.kind === 'oil')] }, h.port);
  h.move(cable.triggerX - 34); system.update(16);
  for (let i = 0; i < 5; i++) system.update(50);
  const clock = system.getDebugState()[0].elapsedMs; h.setActive(false); system.update(50); assert.equal(system.getDebugState()[0].elapsedMs, clock); h.setActive(true);
  h.port.kill = (id, risk) => { if (risk === 'attack' && h.port.isDashing()) return false; h.deaths.push({ id, risk }); h.move(96); system.resetForAttempt(96); return true; };
  h.setDashing(true); h.move(cable.rect.x); assert.equal(system.update(16), false); assert.equal(h.deaths.length, 0);
  h.setDashing(false); assert.equal(system.update(16), true); assert.equal(h.deaths.length, 1);
  h.setDashing(true); h.move(scrap.rect.x); assert.equal(system.update(16), true); assert.equal(h.deaths.at(-1).risk, 'physical');
  const oil = layout.objects.find(o => o.kind === 'oil'); h.move(oil.rect.x + 10); assert.equal(system.sampleSurface().deceleration, 360);
  h.move(96); assert.equal(system.sampleSurface(), null);
  system.destroy(); system.destroy(); assert.ok(cleared >= 3); assert.ok(h.objects.every(o => o.destroyed));
});
