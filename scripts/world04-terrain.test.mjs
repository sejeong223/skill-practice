import assert from 'node:assert/strict';
import test from 'node:test';
import { requireTS, world04Harness } from './world04-test-fixtures.mjs';
const { getWorld04Layout } = requireTS('../src/game/data/world04Scrapyard.ts');
const { createTerrainState, advanceTerrainState } = requireTS('../src/game/systems/world04TerrainState.ts');
const { World04TerrainSystem } = requireTS('../src/game/systems/World04TerrainSystem.ts');
const { overlapRect } = requireTS('../src/game/systems/world04Geometry.ts');
const l = getWorld04Layout('world-04-stage-1'), rise = l.terrain.find(t => t.kind === 'rise');
const rect = (right, bottom = 504) => ({ x: right - 72, y: bottom - 40, width: 72, height: 40 });
const sample = (before, after, bottom = 504, grounded = true) => ({ before: rect(before, bottom), after: rect(after, bottom), grounded, velocityX: 240, velocityY: 0 });
test('rise has zero warning, post-onset 700ms, one-shot and no jump bypass', () => {
  const x = rise.rect.x;
  let s = createTerrainState(rise), step = advanceTerrainState(rise, s, sample(x, x + 55), 50);
  assert.equal(step.state.phase, 'armed'); assert.equal(step.frontRect, null); assert.equal(step.rearRect, null);
  step = advanceTerrainState(rise, step.state, sample(x + 55, x + 60, 411, false), 50);
  assert.equal(step.state.elapsedMs, 0); assert.equal(step.state.phase, 'retreat'); assert.equal(step.frontRect.height, 320); assert.equal(step.rearRect, null);
  step = advanceTerrainState(rise, step.state, sample(x + 60, x + 60), 699);
  assert.equal(step.rearRect, null);
  step = advanceTerrainState(rise, step.state, sample(x + 60, x + 60), 1);
  assert.equal(step.state.phase, 'strike'); assert.equal(step.rearRect.height, 320);
  for (const bottom of [504, 411, 344]) assert.ok(step.dangerRects.some(r => overlapRect(rect(x + 60, bottom), r)));
  assert.equal(step.dangerRects.some(r => overlapRect(rect(x), r)), false);
  step = advanceTerrainState(rise, step.state, sample(x, x), 480);
  assert.equal(step.state.phase, 'spent'); assert.equal(step.frontRect, null); assert.deepEqual(step.dangerRects, []);
  assert.equal(advanceTerrainState(rise, step.state, sample(x, x + 90), 50).state.phase, 'spent');
  assert.equal(createTerrainState(rise).phase, 'armed');
});
test('large delta preserves crossed strike, invalid delta cannot advance clock', () => {
  const x = rise.rect.x;
  const started = advanceTerrainState(rise, createTerrainState(rise), sample(x, x + 60), 16);
  const end = advanceTerrainState(rise, started.state, sample(x + 60, x + 60), 2000);
  assert.equal(end.state.phase, 'spent'); assert.equal(end.dangerRects.length, 2);
  assert.equal(advanceTerrainState(rise, started.state, sample(x, x), NaN).state.elapsedMs, 0);
});
test('collapse is grounded-only, immediate collision removal and symmetric approach', () => {
  const d = l.terrain.find(t => t.kind === 'collapse'), x = d.rect.x;
  assert.equal(advanceTerrainState(d, createTerrainState(d), sample(x - 13, x - 10, 411, false), 16).bridgeEnabled, true);
  const step = advanceTerrainState(d, createTerrainState(d), sample(x - 13, x - 10), 16);
  assert.equal(step.bridgeEnabled, false); assert.equal(step.fallProgress, 0);
  assert.equal(advanceTerrainState(d, step.state, sample(x, x), 180).state.phase, 'collapsed');
  const right = sample(x + d.rect.width + 85, x + d.rect.width + 80); right.velocityX = -240;
  assert.equal(advanceTerrainState(d, createTerrainState(d), right, 16).bridgeEnabled, false);
});
test('runtime clamp, paused clock, death during synchronous reset, hole body ownership and disposal', () => {
  const h = world04Harness(rise.rect.x), system = new World04TerrainSystem(h.scene, h.player, l, h.port);
  const x = rise.rect.x; h.move(x + 70); system.update(50);
  assert.equal(h.player.body.x + 72, x + 80);
  h.setActive(false); system.update(50); assert.equal(system.getDebugState().find(e => e.id === rise.id).elapsedMs, 0);
  h.setActive(true); h.setDashing(true);
  h.port.kill = (id, risk) => { h.deaths.push({ id, risk }); h.move(96); system.resetForAttempt(96); return true; };
  let died = false; for (let i = 0; i < 15 && !died; i++) died = system.update(50);
  assert.equal(died, true); assert.equal(h.deaths.length, 1); assert.equal(h.deaths[0].risk, 'physical');
  assert.ok(system.getDebugState().every(e => e.state === 'armed'));
  const d = l.terrain.find(t => t.kind === 'collapse'); h.move(d.rect.x - 50); system.resetForAttempt(h.player.x); h.move(d.rect.x - 45); system.update(16);
  const bridges = h.objects.filter(o => o.body && o.x === d.rect.x && o.width === d.rect.width);
  assert.equal(bridges.length, 1); assert.equal(bridges[0].body.enable, false);
  system.resetForAttempt(h.player.x); assert.equal(bridges[0].body.enable, true);
  system.destroy(); system.destroy(); assert.ok(h.objects.every(o => o.destroyed)); assert.ok(h.colliders.every(c => c.destroyed));
});
